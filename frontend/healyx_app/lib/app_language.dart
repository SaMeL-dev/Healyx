  static final ValueNotifier<String> currentLang = ValueNotifier('ko');

  // 앱 시작할 때 저장된 언어 불러오기
  static Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString('language_pref') ?? 'ko';
    currentLang.value = saved;
  }

  // 언어 선택할 때 호출 (저장 + 전역 상태 업데이트)
  static Future<void> setLang(String code) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('language_pref', code);
    currentLang.value = code;
  }

